export function generateTikTokScript(newsItem) {
  const title = newsItem.title;
  const description = newsItem.description || 'Свежее технологическое событие.';

  return `🎬 **СТРУКТУРА TikTok-РОЛИКА (9:16)**

🪝 **Хук (0–3 секунды):**
«Вы не поверите, что произошло в мире технологий!» (Показать крупным планом заголовок: *${title}*)

🗣️ **Основная часть (3–15 секунд):**
Коротко суть: ${description.slice(0, 150)}...

🤯 **Интересная деталь (15–25 секунд):**
Почему об этом говорят эксперты и блогеры прямо сейчас.

🎯 **Финал и призыв (25–30 секунд):**
«Как думаете, это прорыв или очередной хайп? Пишите в комментариях!»

🎨 **Визуальный ряд и монтаж:**
• Вертикальное видео 9:16.
• Динамичные субтитры с акцентами ключевых слов.
• На фон — трендовый не отвлекающий луп из игр или подложка Synthwave.

⏱️ **Примерная длительность:** 25-30 секунд.`;
}
